<#
.SYNOPSIS
    Turns the string catalogues into per-language .resw files.

.DESCRIPTION
    One JSON file per executable holds every string in every language, so adding a
    language means adding a tag to each entry rather than hand-editing a dozen XML
    files. This script expands them into Strings\<lang>\Resources.resw, which is
    what the Windows App SDK resource compiler consumes.

    A missing translation is an error, not a silent fallback: it is far easier to
    notice here than in a shipped build where the string quietly turns English.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Generate-Resources.ps1
#>
[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot

$catalogues = @(
    @{ Json = 'strings.host.json';    Project = 'Mica.Host' }
    @{ Json = 'strings.builder.json'; Project = 'Mica.Builder' }
)

function ConvertTo-Resw {
    param([hashtable]$Entries)

    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
    [void]$sb.AppendLine('<!-- Generated by tools/Generate-Resources.ps1. Edit tools/strings.*.json instead. -->')
    [void]$sb.AppendLine('<root>')
    [void]$sb.AppendLine('  <resheader name="resmimetype">')
    [void]$sb.AppendLine('    <value>text/microsoft-resx</value>')
    [void]$sb.AppendLine('  </resheader>')
    [void]$sb.AppendLine('  <resheader name="version">')
    [void]$sb.AppendLine('    <value>2.0</value>')
    [void]$sb.AppendLine('  </resheader>')
    [void]$sb.AppendLine('  <resheader name="reader">')
    [void]$sb.AppendLine('    <value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>')
    [void]$sb.AppendLine('  </resheader>')
    [void]$sb.AppendLine('  <resheader name="writer">')
    [void]$sb.AppendLine('    <value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value>')
    [void]$sb.AppendLine('  </resheader>')

    foreach ($key in ($Entries.Keys | Sort-Object)) {
        $value = [System.Security.SecurityElement]::Escape($Entries[$key])
        [void]$sb.AppendLine("  <data name=""$key"" xml:space=""preserve"">")
        [void]$sb.AppendLine("    <value>$value</value>")
        [void]$sb.AppendLine('  </data>')
    }

    [void]$sb.AppendLine('</root>')
    return $sb.ToString()
}

$problems = New-Object System.Collections.ArrayList

foreach ($catalogue in $catalogues) {
    $path = Join-Path $PSScriptRoot $catalogue.Json
    $json = Get-Content -LiteralPath $path -Raw -Encoding UTF8 | ConvertFrom-Json

    $languages = $json.'_languages'
    $keys = $json.PSObject.Properties.Name | Where-Object { -not $_.StartsWith('_') }

    Write-Host "$($catalogue.Project): $($keys.Count) strings x $($languages.Count) languages"

    foreach ($language in $languages) {
        $entries = @{}

        foreach ($key in $keys) {
            $translations = $json.$key
            $value = $translations.$language

            if ([string]::IsNullOrWhiteSpace($value)) {
                [void]$problems.Add("$($catalogue.Json): '$key' has no '$language' translation")
                continue
            }

            # The catalogue is JSON, so a literal newline is written \n; .resw wants
            # the real character.
            $entries[$key] = $value -replace '\\n', "`n"
        }

        if ($Check) {
            continue
        }

        $folder = Join-Path $root "$($catalogue.Project)\Strings\$language"
        New-Item -ItemType Directory -Force -Path $folder | Out-Null

        $file = Join-Path $folder 'Resources.resw'
        $utf8 = New-Object System.Text.UTF8Encoding($false)
        [System.IO.File]::WriteAllText($file, (ConvertTo-Resw $entries), $utf8)
    }
}

if ($problems.Count -gt 0) {
    $problems | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
    throw "$($problems.Count) missing translation(s)."
}

Write-Host ""
Write-Host $(if ($Check) { 'Catalogues are complete.' } else { 'Resource files written.' })
